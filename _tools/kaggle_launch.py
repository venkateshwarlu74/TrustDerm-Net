"""Build and push a self-contained Kaggle kernel that runs one stage of the TrustDerm-Net pipeline.

The code folder is zipped and embedded in the kernel (no separate code dataset to keep in sync).
Outputs of earlier stages are attached as kernel sources and linked into /kaggle/working.

Usage:
  python kaggle_launch.py prep                      # CPU: manifest, preprocessing, splits
  python kaggle_launch.py smoke                     # GPU: 1-epoch end-to-end check
  python kaggle_launch.py teacher --folds 0 1 2     # GPU
  python kaggle_launch.py student --folds 0 1 2     # GPU, needs teacher outputs
  python kaggle_launch.py custom --name x --cmd "python train.py ..." [--sources user/kernel ...] [--gpu]
"""
import argparse, base64, io, json, os, subprocess, sys, zipfile

USER = os.environ.get("KAGGLE_USERNAME", "your-kaggle-username")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODE = os.path.join(ROOT, "code")
BUILD = os.path.join(ROOT, "_kaggle_build")
KAGGLE = os.path.join(os.environ["APPDATA"], "Python", f"Python{sys.version_info.major}{sys.version_info.minor}",
                      "Scripts", "kaggle.exe")
DATASETS = ["kmader/skin-cancer-mnist-ham10000", "mahdavi1202/skin-cancer", f"{USER}/derm7pt-release-v0"]
COMPETITIONS = ["siim-isic-melanoma-classification"]

RUNNER = r'''
# Auto-generated by kaggle_launch.py: stage "{stage}"
import base64, glob, io, os, shutil, subprocess, sys, time, zipfile
W = "/kaggle/working"
zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE))).extractall(W)
os.chdir(os.path.join(W, "code"))

def find(pattern):
    for depth in ("*", "*/*", "*/*/*", "*/*/*/*"):
        hits = sorted(glob.glob(os.path.join("/kaggle/input", depth, pattern)))
        if hits:
            return hits
    return []

# link outputs of earlier stages (manifest + image cache + checkpoints)
links = []
man = find("manifest.csv")
man = [p for p in man if os.path.exists(os.path.join(os.path.dirname(p), "cache.zip"))] or man   # prep output first
print("manifest:", man[:1], flush=True)
if man and not os.path.exists(os.path.join(W, "manifest.csv")):
    shutil.copy(man[0], W)
    cz = os.path.join(os.path.dirname(man[0]), "cache.zip")
    if os.path.exists(cz) and not os.path.exists(os.path.join(W, "cache")):
        t0 = time.time()
        zipfile.ZipFile(cz).extractall("/tmp")              # /tmp/cache/...
        os.symlink("/tmp/cache", os.path.join(W, "cache")); links.append(os.path.join(W, "cache"))
        print(f"image cache unpacked in {{(time.time() - t0) / 60:.1f}} min", flush=True)
os.makedirs(os.path.join(W, "ckpt"), exist_ok=True)
for ck in find("ckpt/*.pt"):
    dst = os.path.join(W, "ckpt", os.path.basename(ck))
    if not os.path.exists(dst):
        os.symlink(ck, dst); links.append(dst)

log = open(os.path.join(W, "run_log.txt"), "a")
ok = True
for cmd in COMMANDS:
    t0 = time.time()
    print(f"\n===== {{cmd}}", flush=True); log.write(f"\n===== {{cmd}}\n"); log.flush()
    p = subprocess.Popen(cmd, shell=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        print(line, end="", flush=True); log.write(line); log.flush()
    rc = p.wait()
    msg = f"===== exit {{rc}} after {{(time.time() - t0) / 60:.1f}} min"
    print(msg, flush=True); log.write(msg + "\n"); log.flush()
    if rc != 0:
        ok = False
        break
for l in links:      # do not duplicate earlier outputs in this kernel's output
    os.unlink(l)
cache = os.path.join(W, "cache")
if os.path.isdir(cache) and not os.path.islink(cache):   # prep stage: ship the cache as one archive
    with zipfile.ZipFile(os.path.join(W, "cache.zip"), "w", zipfile.ZIP_STORED) as z:
        for root, _, files in os.walk(cache):
            for f in files:
                p = os.path.join(root, f)
                z.write(p, os.path.relpath(p, W))
    shutil.rmtree(cache)
shutil.rmtree(os.path.join(W, "code"), ignore_errors=True)
print("ALL DONE" if ok else "FAILED", flush=True)
'''


def code_zip_b64():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(CODE)):
            if f.endswith((".py", ".md", ".csv")):
                z.write(os.path.join(CODE, f), "code/" + f)
    return base64.b64encode(buf.getvalue()).decode()


def push(name, commands, gpu, sources):
    folder = os.path.join(BUILD, name)
    os.makedirs(folder, exist_ok=True)
    script = (f"CODE = {code_zip_b64()!r}\nCOMMANDS = {commands!r}\n" + RUNNER.format(stage=name))
    with open(os.path.join(folder, "run.py"), "w", encoding="utf-8") as f:
        f.write(script)
    meta = {"id": f"{USER}/{name}", "title": name, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": gpu, "enable_internet": True,
            "dataset_sources": DATASETS,
            "competition_sources": [] if os.environ.get("TD_NO_COMP") else COMPETITIONS,
            "kernel_sources": [s if "/" in s else f"{USER}/{s}" for s in sources]}
    with open(os.path.join(folder, "kernel-metadata.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print(f"pushing {USER}/{name}  gpu={gpu}  sources={meta['kernel_sources']}")
    subprocess.run([KAGGLE, "kernels", "push", "-p", folder], check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stage", choices=["prep", "smoke", "teacher", "student", "custom"])
    ap.add_argument("--folds", nargs="+", type=int, default=[0])
    ap.add_argument("--name")
    ap.add_argument("--cmd", nargs="+", default=[])
    ap.add_argument("--sources", nargs="*", default=[])
    ap.add_argument("--gpu", action="store_true")
    ap.add_argument("--extra", default="", help="extra flags appended to every train command")
    a = ap.parse_args()
    folds = "-".join(map(str, a.folds))
    if a.stage == "prep":
        push("trustderm-prep", ["python build_manifest.py", "python preprocess.py --workers 4",
                                "python make_splits.py"], gpu=False, sources=[])
    elif a.stage == "smoke":
        push("trustderm-smoke", [
            "python train.py --role teacher --fold 0 --epochs 1 --max_train 256 --tag smoke_teacher",
            "python train.py --role student --fold 0 --epochs 1 --max_train 256 --tag smoke_student "
            "--teacher_ckpt /kaggle/working/ckpt/smoke_teacher_fold0.pt",
            "python evaluate.py --tag smoke_student",
            "python efficiency.py --ckpt /kaggle/working/ckpt/smoke_student_fold0.pt"],
            gpu=True, sources=["trustderm-prep"])
    elif a.stage == "teacher":
        push(f"trustderm-teacher-f{folds}", [f"python train.py --role teacher --fold {k} {a.extra}" for k in a.folds],
             gpu=True, sources=["trustderm-prep"])
    elif a.stage == "student":
        cmds = [f"python train.py --role student --fold {k} --teacher_ckpt /kaggle/working/ckpt/teacher_fold{k}.pt "
                f"{a.extra}" for k in a.folds]
        push(f"trustderm-student-f{folds}", cmds + ["python evaluate.py --tag student"], gpu=True,
             sources=["trustderm-prep"] + a.sources)
    else:
        push(a.name, a.cmd, gpu=a.gpu, sources=a.sources)


if __name__ == "__main__":
    main()
